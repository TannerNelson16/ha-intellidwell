def resolve_weather_options(raw_opts: dict[str, Any] | None) -> dict[str, Any]:
    """Return full weather configuration dictionary merged with defaults."""
    resolved = dict(WEATHER_OPTION_DEFAULTS)
    if raw_opts:
        for key in WEATHER_OPTION_DEFAULTS:
            if key in raw_opts and raw_opts[key] is not None:
                resolved[key] = raw_opts[key]
    return resolved
